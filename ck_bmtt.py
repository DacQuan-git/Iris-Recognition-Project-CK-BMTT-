def authenticate(image_stem):
    query_code = extract_iris_code(image_stem)

    distances = []

    for template in db_codes:
        distance, shift = hamming_distance(
            query_code,
            template
        )

        distances.append((distance, shift))

    best_index = np.argmin([d[0] for d in distances])

    best_distance, best_shift = distances[best_index]
    matched_user = str(db_owners[best_index])

    if best_distance <= THRESHOLD:
        return {
            "status": "AUTHORIZED",
            "user": matched_user,
            "distance": best_distance,
            "shift": best_shift
        }

    return {
        "status": "UNAUTHORIZED",
        "user": None,
        "distance": best_distance,
        "shift": best_shift
    }
