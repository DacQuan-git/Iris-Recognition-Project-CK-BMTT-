def hamming_distance(code1, code2, max_shift=32):
    if code1.shape != code2.shape:
        raise ValueError("Iris Code dimensions must match")

    distances = []

    for shift in range(-max_shift, max_shift + 1):
        shifted = np.roll(code2, shift, axis=1)
        distance = np.mean(code1 != shifted)
        distances.append((float(distance), shift))

    return min(distances)

def extract_iris_code(stem):
    image_path = IMG_DIR / f"{stem}.jpg"
    mask_path = MASK_DIR / f"{stem}.png"

    if not image_path.exists() or not mask_path.exists():
        raise FileNotFoundError(f"Missing image or mask: {stem}")

    img = cv2.imread(str(image_path), cv2.IMREAD_GRAYSCALE)
    msk = cv2.imread(str(mask_path), cv2.IMREAD_GRAYSCALE)

    if img is None or msk is None:
        raise ValueError(f"Cannot read image or mask: {stem}")

    normalized, _ = normalize_iris(img, msk)
    return encode_iris(normalized)
