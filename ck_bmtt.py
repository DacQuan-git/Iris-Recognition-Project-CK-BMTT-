def normalize_iris(image, mask, radial_res=64, angular_res=512):
    binary = np.where(mask > 127, 255, 0).astype(np.uint8)

    contours, hierarchy = cv2.findContours(
        binary, cv2.RETR_TREE, cv2.CHAIN_APPROX_NONE
    )

    if hierarchy is None:
        raise ValueError("Invalid iris mask")

    outer_idx = max(
        range(len(contours)),
        key=lambda i: cv2.contourArea(contours[i])
    )

    inner_idx = hierarchy[0][outer_idx][2]

    if inner_idx < 0:
        raise ValueError("Cannot find pupil boundary")

    M = cv2.moments(contours[inner_idx])

    if M["m00"] == 0:
        raise ValueError("Invalid pupil contour")

    cx = M["m10"] / M["m00"]
    cy = M["m01"] / M["m00"]

    h, w = image.shape
    angles = np.linspace(0, 2 * np.pi, angular_res, endpoint=False)
    radii = np.arange(0, int(np.hypot(h, w)), 0.5, dtype=np.float32)

    ray_x = (cx + np.cos(angles)[:, None] * radii).astype(np.float32)
    ray_y = (cy + np.sin(angles)[:, None] * radii).astype(np.float32)

    sampled_mask = cv2.remap(
        binary, ray_x, ray_y,
        cv2.INTER_NEAREST,
        borderMode=cv2.BORDER_CONSTANT,
        borderValue=0
    )

    inner_r = np.zeros(angular_res, dtype=np.float32)
    outer_r = np.zeros(angular_res, dtype=np.float32)

    for i, row in enumerate(sampled_mask):
        indices = np.flatnonzero(row > 0)

        if len(indices) == 0:
            raise ValueError("Invalid iris boundary")

        inner_r[i] = radii[indices[0]]
        outer_r[i] = radii[indices[-1]]

    if np.any(outer_r <= inner_r):
        raise ValueError("Invalid iris region")

    rho = np.linspace(0.05, 0.95, radial_res)[:, None]

    r = inner_r[None, :] + rho * (outer_r - inner_r)[None, :]

    map_x = (cx + np.cos(angles)[None, :] * r).astype(np.float32)
    map_y = (cy + np.sin(angles)[None, :] * r).astype(np.float32)

    normalized = cv2.remap(
        image, map_x, map_y,
        cv2.INTER_LINEAR,
        borderMode=cv2.BORDER_CONSTANT,
        borderValue=0
    )

    debug = cv2.cvtColor(image, cv2.COLOR_GRAY2RGB)
    cv2.drawContours(debug, [contours[outer_idx]], -1, (0, 255, 0), 1)
    cv2.drawContours(debug, [contours[inner_idx]], -1, (255, 0, 0), 1)

    return normalized, debug
