#Chúng ta sử dụng Log-Gabor Filter để trích xuất đặc trưng kết cấu và chuyển chúng thành các bit 0 và 1.
def encode_iris(normalized, f0=0.1, sigma_on_f=0.55):
    image = normalized.astype(np.float32)

    image -= image.mean(axis=1, keepdims=True)

    rows, cols = image.shape

    frequencies = np.fft.fftfreq(cols)
    log_gabor = np.zeros(cols, dtype=np.float32)

    positive = frequencies > 0

    log_gabor[positive] = np.exp(
        -(np.log(frequencies[positive] / f0) ** 2)
        / (2 * np.log(sigma_on_f) ** 2)
    )

    spectrum = np.fft.fft(image, axis=1)
    response = np.fft.ifft(
        spectrum * log_gabor[None, :],
        axis=1
    )

    code = np.stack([
        response.real >= 0,
        response.imag >= 0
    ], axis=-1)

    return code.astype(np.uint8)
